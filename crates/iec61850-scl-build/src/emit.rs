/// Emits a data attribute as `DataAttribute::new(...)`, or as
/// `DataAttribute::constructed(...)` when its bType is a structure, wrapped
/// into `DataAttribute::array(...)` when it carries a `count`.
///
/// Every bType-to-type, fc-to-FC and trigger-option conversion calls the
/// runtime helper.
fn emit_da_expr(
    da: &RawDaDef,
    dtt: &DataTypeTemplates,
    values: Option<&[RawDataInstance]>,
) -> Result<TokenStream, CompileError> {
    let count = element_count(da.count.as_ref(), values, da.span, "DA").map_err(model_error)?;
    Ok(emit_array_of(
        emit_da_element(da, dtt, instance_children(values, &da.name))?,
        count,
    ))
}

/// Emits one element of a data attribute; see [`emit_da_expr`].
fn emit_da_element(
    da: &RawDaDef,
    dtt: &DataTypeTemplates,
    values: Option<&[RawDataInstance]>,
) -> Result<TokenStream, CompileError> {
    // The functional constraint goes through the runtime helper; an unknown
    // token becomes an SclParseError.
    let fc = parse_fc(
        &da.fc, da.span,
        // The path only decorates the error message, and the build script has
        // already validated the input, so a placeholder is enough.
        "DA",
    )
    .map_err(model_error)?;
    let fc_tok = emit_fc_value(fc);
    let trg_tok = emit_trg_ops(da.trg_ops);
    let name_lit = da.name.as_str();

    if da.b_type == "Struct" {
        let type_id = da.type_ref.as_deref().ok_or_else(|| {
            CompileError::Emit(format!("DA `{}` has bType=Struct but no type_ref", da.name))
        })?;
        let dat = dtt.da_types.get(type_id).ok_or_else(|| {
            CompileError::Emit(format!(
                "DA `{}` type_ref `{}` is absent from da_types; the resolve stage should have rejected it",
                da.name, type_id
            ))
        })?;
        let child_exprs = dat
            .bdas
            .iter()
            .map(|bda| emit_bda_expr(bda, &fc_tok, dtt, values))
            .collect::<Result<Vec<_>, _>>()?;
        // Matches the runtime path: a constructed DA, then its trigger options.
        return Ok(quote! {
            {
                let mut __da = DataAttribute::constructed(
                    ::std::string::String::from(#name_lit),
                    #fc_tok,
                    ::std::vec![ #( #child_exprs ),* ],
                );
                __da.trg_ops = #trg_tok;
                __da
            }
        });
    }

    // Leaf DA: the type comes from `attribute_type` and the initial value, the
    // `<Val>` of the declaration or the zero value, from
    // `template_initial_value`.
    let dat = attribute_type(&da.b_type, da.type_ref.as_deref(), dtt, da.span, "DA")
        .map_err(model_error)?;
    let dat_tok = emit_dat_value(dat);
    let initial = template_initial_value(
        dat,
        &da.b_type,
        da.type_ref.as_deref(),
        da.default_value.as_deref(),
        dtt,
        da.span,
        "DA",
    )
    .map_err(model_error)?;
    let initial_tok = emit_mms_value(&initial);

    Ok(quote! {
        DataAttribute::new(
            ::std::string::String::from(#name_lit),
            #fc_tok,
            #dat_tok,
            #trg_tok,
            #initial_tok,
        )
    })
}

/// Emits a BDA as a `DataAttribute`, an array of them when it carries a
/// `count`.
///
/// A BDA has no functional constraint of its own and inherits the one of its
/// parent DA or BDA.
fn emit_bda_expr(
    bda: &RawBda,
    parent_fc: &TokenStream,
    dtt: &DataTypeTemplates,
    values: Option<&[RawDataInstance]>,
) -> Result<TokenStream, CompileError> {
    let count = element_count(bda.count.as_ref(), values, bda.span, "BDA").map_err(model_error)?;
    Ok(emit_array_of(
        emit_bda_element(bda, parent_fc, dtt, instance_children(values, &bda.name))?,
        count,
    ))
}

/// Emits one element of a BDA; see [`emit_bda_expr`].
fn emit_bda_element(
    bda: &RawBda,
    parent_fc: &TokenStream,
    dtt: &DataTypeTemplates,
    values: Option<&[RawDataInstance]>,
) -> Result<TokenStream, CompileError> {
    let name_lit = bda.name.as_str();

    if bda.b_type == "Struct" {
        let type_id = bda.type_ref.as_deref().ok_or_else(|| {
            CompileError::Emit(format!(
                "BDA `{}` has bType=Struct but no type_ref",
                bda.name
            ))
        })?;
        let dat = dtt.da_types.get(type_id).ok_or_else(|| {
            CompileError::Emit(format!(
                "BDA `{}` type_ref `{}` is absent from da_types; the resolve stage should have rejected it",
                bda.name, type_id
            ))
        })?;
        let child_exprs = dat
            .bdas
            .iter()
            .map(|child| emit_bda_expr(child, parent_fc, dtt, values))
            .collect::<Result<Vec<_>, _>>()?;
        return Ok(quote! {
            DataAttribute::constructed(
                ::std::string::String::from(#name_lit),
                #parent_fc,
                ::std::vec![ #( #child_exprs ),* ],
            )
        });
    }

    let dat = attribute_type(&bda.b_type, bda.type_ref.as_deref(), dtt, bda.span, "BDA")
        .map_err(model_error)?;
    let dat_tok = emit_dat_value(dat);
    let initial = template_initial_value(
        dat,
        &bda.b_type,
        bda.type_ref.as_deref(),
        bda.default_value.as_deref(),
        dtt,
        bda.span,
        "BDA",
    )
    .map_err(model_error)?;
    let initial_tok = emit_mms_value(&initial);

    Ok(quote! {
        DataAttribute::new(
            ::std::string::String::from(#name_lit),
            #parent_fc,
            #dat_tok,
            TrgOps::NONE,
            #initial_tok,
        )
    })
}

