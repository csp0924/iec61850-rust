//! Emit layer: walks a `ResolvedScl` once and produces the `TokenStream` that
//! builds an `IedModel`.
//!
//! Structure:
//!
//! - [`emit_file`] - top level; one `pub fn build_<X>_model() -> IedModel` per IED
//! - `emit_ied_fn` - a single IED into a function body
//! - `emit_ld_expr` - a logical device into a `LogicalDeviceBuilder` chain
//! - `emit_ln_expr` - a logical node into a `LogicalNodeBuilder` chain, with its
//!   data sets, four control block kinds, SGCB and DOI overrides
//! - `emit_do_type_expansion` - recursive DO and SDO expansion
//! - `emit_da_expr` / `emit_bda_expr` - DA and BDA, including the recursion into
//!   a constructed bType
//! - `emit_dataset_expr` / `emit_fcda_expr` - data sets and their members
//! - `emit_rcb_expr` / `emit_gocb_expr` / `emit_svcb_expr` / `emit_lcb_expr` /
//!   `emit_sgcb_expr`
//! - `emit_doi_overrides` - the post-build walk that applies DOI, SDI and DAI
//!   default-value overrides
//!
//! Each emit function follows its counterpart in `iec61850_scl::build_model`
//! almost line for line; `let x = build_xxx(arg)?` there becomes
//! `let x_tokens = emit_xxx_expr(arg)?` here. Every conversion from a string to
//! an enum, and from a bType to a data attribute type, calls the same
//! `__build_internals` helper the runtime path uses, so generated and runtime
//! models cannot diverge.

use proc_macro2::TokenStream;
use quote::{format_ident, quote};

use iec61850_scl::__build_internals::{
    parse_fc, parse_val_for_b_type, pick_val_for_no_sgroup, MmsValue,
};
use iec61850_scl::raw::{
    DataTypeTemplates, RawBda, RawDaDef, RawDaType, RawDai, RawDataInstance, RawDataSet, RawDoDef,
    RawDoType, RawFcda, RawGseControl, RawIed, RawLogControl, RawLogicalDevice, RawLogicalNode,
    RawReportControlBlock, RawSampledValueControl, RawScl, RawSdi, RawSdoDef, RawSettingControl,
};
use iec61850_scl::ResolvedScl;

use crate::tokens::{
    emit_dat_value, emit_default_mms_value, emit_fc_value, emit_mms_value, emit_opt_flds,
    emit_report_trg_ops, emit_trg_ops,
};
use crate::{CompileBuilder, CompileError};

