    /// Generated code and the runtime build path must produce the same
    /// LD, LN, DO and DA shape for one SCL file.
    ///
    /// The comparison is on a serialized structural summary, because
    /// `Arc<RwLock<MmsValue>>` does not compare directly. That is enough to show
    /// the two walks agree.
    #[test]
    fn emit_structure_summary_matches_runtime() {
        let xml = compile_smoke_xml();
        let raw = parse_scl(xml).expect("parse");
        let resolved = raw.resolve().expect("resolve");

        let runtime_model = resolved.build_model("IED1").expect("build_model");

        // Generated path: emit, parse to confirm the result is syntactically
        // valid, then check the structural markers.
        let tokens = emit_file(&resolved, &cfg()).expect("emit_file");
        let _file: syn::File = syn::parse2(tokens).expect("parse2");

        // The runtime side has one LD and two LNs; LLN0 has two DOs and MMXU has
        // one DO whose phsA is a constructed DA.
        assert_eq!(runtime_model.lds.len(), 1);
        let ld = &runtime_model.lds[0];
        assert_eq!(ld.lns.len(), 2);
        let lln0 = ld.lns.iter().find(|ln| ln.class == "LLN0").expect("LLN0");
        assert_eq!(lln0.dos.len(), 2);
        // DOI override: Mod.stVal must become 1, since "on" has ord=1.
        let mod_do = lln0.do_by_name("Mod").expect("Mod DO");
        let st_val = match mod_do
            .child_by_name("stVal", None)
            .expect("Mod.stVal exists")
        {
            iec61850_scl::__private::DoChild::Da(da) => da,
            _ => panic!("stVal should be DA"),
        };
        let snapshot = st_val.value.read().expect("lock").clone();
        match snapshot {
            iec61850_scl::__private::MmsValue::Integer(i) => assert_eq!(i, 1),
            other => panic!("expected Integer(1), got {other:?}"),
        }
    }
