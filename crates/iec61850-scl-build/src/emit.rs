/// Emits a logical node as `{ let mut __ln = ...; __ln.add_do(...); ...;
/// let __ln = __ln.build()...; <DOI overrides>; __ln }`.
fn emit_ln_expr(
    ln: &RawLogicalNode,
    dtt: &DataTypeTemplates,
    ld_inst: &str,
    cfg: &CompileBuilder,
) -> Result<TokenStream, CompileError> {
    let prefix_lit = ln.prefix.as_deref().unwrap_or("");
    let ln_class_lit = ln.ln_class.as_str();
    let inst_lit = ln.inst.as_str();

    // The resolve stage has already checked that ln_type_ref exists.
    let lnt = dtt.ln_node_types.get(&ln.ln_type_ref).ok_or_else(|| {
        CompileError::Emit(format!(
            "LN ln_type_ref `{}` is absent from ln_node_types; the resolve stage should have rejected it",
            ln.ln_type_ref
        ))
    })?;

    // The DO order inside an LNodeType comes from the SCL and is preserved;
    // determinism is handled at logical device and logical node level.
    let do_exprs = lnt
        .dos
        .iter()
        .map(|do_def| emit_do_expr(do_def, dtt))
        .collect::<Result<Vec<_>, _>>()?;

    // Data sets, sorted for determinism.
    let mut datasets: Vec<&RawDataSet> = ln.data_sets.iter().collect();
    if cfg.is_deterministic() {
        datasets.sort_by(|a, b| a.name.cmp(&b.name));
    }
    let dataset_exprs = datasets
        .iter()
        .map(|ds| emit_dataset_expr(ds, ld_inst, ln))
        .collect::<Result<Vec<_>, _>>()?;

    // The four control block kinds, sorted for determinism.
    let rcb_exprs = sorted_by_name(ln.report_controls.iter(), cfg, |r| r.name.as_str())
        .into_iter()
        .map(emit_rcb_expr)
        .collect::<Vec<_>>();
    let gocb_exprs = sorted_by_name(ln.gse_controls.iter(), cfg, |g| g.name.as_str())
        .into_iter()
        .map(emit_gocb_expr)
        .collect::<Vec<_>>();
    let svcb_exprs = sorted_by_name(ln.smv_controls.iter(), cfg, |s| s.name.as_str())
        .into_iter()
        .map(emit_svcb_expr)
        .collect::<Vec<_>>();
    let lcb_exprs = sorted_by_name(ln.log_controls.iter(), cfg, |l| l.name.as_str())
        .into_iter()
        .map(emit_lcb_expr)
        .collect::<Vec<_>>();

    let sgcb_apply = match ln.setting_control.as_ref() {
        Some(sgcb) => {
            let expr = emit_sgcb_expr(sgcb, ln, ld_inst)?;
            Some(quote! { __ln = __ln.set_sgcb(#expr); })
        }
        None => None,
    };

    // DOI overrides mutate the `Arc<RwLock<MmsValue>>` after `ln.build()`.
    let override_stmts = emit_doi_overrides(ln, dtt, ld_inst)?;

    Ok(quote! {
        {
            let mut __ln = LogicalNodeBuilder::new(#prefix_lit, #ln_class_lit, #inst_lit);
            #( __ln = __ln.add_do(#do_exprs); )*
            #( __ln = __ln.add_dataset(#dataset_exprs); )*
            #( __ln = __ln.add_rcb(#rcb_exprs); )*
            #( __ln = __ln.add_gocb(#gocb_exprs); )*
            #( __ln = __ln.add_svcb(#svcb_exprs); )*
            #( __ln = __ln.add_lcb(#lcb_exprs); )*
            #sgcb_apply
            let __ln = __ln.build().expect("codegen: LogicalNodeBuilder::build failed");
            #( #override_stmts )*
            __ln
        }
    })
}

