fn emit_rcb_expr(r: &RawReportControlBlock) -> TokenStream {
    let name = r.name.as_str();
    let is_buffered = r.buffered;
    let dataset_ref = r.dat_set.clone().unwrap_or_default();
    let conf_rev = r.conf_rev;
    let rpt_id = r.rpt_id.clone().unwrap_or_default();
    let trg_ops_tok = emit_report_trg_ops(r.trg_ops);
    let opt_flds_tok = emit_opt_flds(r.opt_fields);
    let buf_tm_ms = r.buf_time;
    let intg_pd_ms = r.intg_pd;
    quote! {
        ReportControlBlock {
            name: ::std::string::String::from(#name),
            is_buffered: #is_buffered,
            dataset_ref: ::std::string::String::from(#dataset_ref),
            conf_rev: #conf_rev,
            rpt_id: ::std::string::String::from(#rpt_id),
            trg_ops: #trg_ops_tok,
            opt_flds: #opt_flds_tok,
            buf_tm_ms: #buf_tm_ms,
            intg_pd_ms: #intg_pd_ms,
        }
    }
}

fn emit_gocb_expr(g: &RawGseControl) -> TokenStream {
    let name = g.name.as_str();
    let dataset_ref = g.data_set.as_str();
    let conf_rev = g.conf_rev;
    // The SCL carries no goID, so the control block name is used instead.
    let go_id = g.name.as_str();
    quote! {
        GooseControlBlock {
            name: ::std::string::String::from(#name),
            dataset_ref: ::std::string::String::from(#dataset_ref),
            conf_rev: #conf_rev,
            go_id: ::std::string::String::from(#go_id),
        }
    }
}

fn emit_svcb_expr(s: &RawSampledValueControl) -> TokenStream {
    let name = s.name.as_str();
    let dataset_ref = s.data_set.as_str();
    let conf_rev = s.conf_rev;
    let sv_id = s.smv_id.as_str();
    let is_multicast = s.multicast;
    quote! {
        SvControlBlock {
            name: ::std::string::String::from(#name),
            dataset_ref: ::std::string::String::from(#dataset_ref),
            conf_rev: #conf_rev,
            sv_id: ::std::string::String::from(#sv_id),
            is_multicast: #is_multicast,
        }
    }
}

fn emit_lcb_expr(l: &RawLogControl) -> TokenStream {
    let name = l.name.as_str();
    let dataset_ref = l.data_set.clone().unwrap_or_default();
    let log_ref = l.log_name.clone().unwrap_or_default();
    quote! {
        LogControlBlock {
            name: ::std::string::String::from(#name),
            dataset_ref: ::std::string::String::from(#dataset_ref),
            log_ref: ::std::string::String::from(#log_ref),
        }
    }
}

/// Emits an SGCB, applying the same u8 and u16 range checks as the runtime
/// path.
///
/// A violation panics while the build script runs, so it never reaches the
/// user's binary.
fn emit_sgcb_expr(
    sgcb: &RawSettingControl,
    _ln: &RawLogicalNode,
    _ld_inst: &str,
) -> Result<TokenStream, CompileError> {
    let num_of_sg = u8::try_from(sgcb.num_of_sgs).map_err(|_| {
        CompileError::Emit(format!(
            "SGCB numOfSGs={} is out of range for u8; the standard allows 1 to 255",
            sgcb.num_of_sgs
        ))
    })?;
    let act_sg = u8::try_from(sgcb.act_sg).map_err(|_| {
        CompileError::Emit(format!(
            "SGCB actSG={} is out of range for u8; the standard allows 1 to 255",
            sgcb.act_sg
        ))
    })?;
    let has_resv_tms = sgcb.resv_tms.is_some();
    // Matching the runtime path: a value above u16::MAX is clamped, and a
    // missing value defaults to 60 s.
    let default_resv_tms_s: u16 = sgcb
        .resv_tms
        .map(|v| {
            if v > u16::MAX as u32 {
                u16::MAX
            } else {
                v as u16
            }
        })
        .unwrap_or(60);

    Ok(quote! {
        SettingGroupControlBlock {
            num_of_sg: #num_of_sg,
            act_sg: #act_sg,
            has_resv_tms: #has_resv_tms,
            default_resv_tms_s: #default_resv_tms_s,
        }
    })
}

