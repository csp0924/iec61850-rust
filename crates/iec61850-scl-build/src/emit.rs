/// Emits a data attribute as `DataAttribute::new(...)`, or as
/// `DataAttribute::constructed(...)` when its bType is a structure.
///
/// Every bType-to-type, fc-to-FC and trigger-option conversion calls the
/// runtime helper.
fn emit_da_expr(da: &RawDaDef, dtt: &DataTypeTemplates) -> Result<TokenStream, CompileError> {
    // The functional constraint goes through the runtime helper; an unknown
    // token becomes an SclParseError.
    let fc = parse_fc(
        &da.fc, da.span,
        // The path only decorates the error message, and the build script has
        // already validated the input, so a placeholder is enough.
        "DA",
    )
    .map_err(CompileError::ResolveScl)?;
    let fc_tok = emit_fc_value(fc);
    let trg_tok = emit_trg_ops(da.trg_ops);
    let name_lit = da.name.as_str();

    if da.b_type == "Struct" {
        let type_id = da.type_ref.as_deref().ok_or_else(|| {
            CompileError::Emit(format!("DA `{}` has bType=Struct but no type_ref", da.name))
        })?;
        let dat = dtt.da_types.get(type_id).ok_or_else(|| {
            CompileError::Emit(format!(
                "DA `{}` type_ref `{}` is absent from da_types; the resolve stage should have rejected it",
                da.name, type_id
            ))
        })?;
        let child_exprs = dat
            .bdas
            .iter()
            .map(|bda| emit_bda_expr(bda, &fc_tok, dtt))
            .collect::<Result<Vec<_>, _>>()?;
        // Matches the runtime path: a constructed DA, then its trigger options.
        return Ok(quote! {
            {
                let mut __da = DataAttribute::constructed(
                    ::std::string::String::from(#name_lit),
                    #fc_tok,
                    ::std::vec![ #( #child_exprs ),* ],
                );
                __da.trg_ops = #trg_tok;
                __da
            }
        });
    }

    // Leaf DA: the type comes from `b_type_to_dat` and the initial value from
    // `emit_default_mms_value`.
    let dat = iec61850_scl::__build_internals::b_type_to_dat(&da.b_type, da.span, "DA")
        .map_err(CompileError::ResolveScl)?;
    let dat_tok = emit_dat_value(dat);
    let initial_tok = emit_default_mms_value(dat);

    Ok(quote! {
        DataAttribute::new(
            ::std::string::String::from(#name_lit),
            #fc_tok,
            #dat_tok,
            #trg_tok,
            #initial_tok,
        )
    })
}

/// Emits a BDA as a `DataAttribute`.
///
/// A BDA has no functional constraint of its own and inherits the one of its
/// parent DA or BDA.
fn emit_bda_expr(
    bda: &RawBda,
    parent_fc: &TokenStream,
    dtt: &DataTypeTemplates,
) -> Result<TokenStream, CompileError> {
    let name_lit = bda.name.as_str();

    if bda.b_type == "Struct" {
        let type_id = bda.type_ref.as_deref().ok_or_else(|| {
            CompileError::Emit(format!(
                "BDA `{}` has bType=Struct but no type_ref",
                bda.name
            ))
        })?;
        let dat = dtt.da_types.get(type_id).ok_or_else(|| {
            CompileError::Emit(format!(
                "BDA `{}` type_ref `{}` is absent from da_types; the resolve stage should have rejected it",
                bda.name, type_id
            ))
        })?;
        let child_exprs = dat
            .bdas
            .iter()
            .map(|child| emit_bda_expr(child, parent_fc, dtt))
            .collect::<Result<Vec<_>, _>>()?;
        return Ok(quote! {
            DataAttribute::constructed(
                ::std::string::String::from(#name_lit),
                #parent_fc,
                ::std::vec![ #( #child_exprs ),* ],
            )
        });
    }

    let dat = iec61850_scl::__build_internals::b_type_to_dat(&bda.b_type, bda.span, "BDA")
        .map_err(CompileError::ResolveScl)?;
    let dat_tok = emit_dat_value(dat);
    let initial_tok = emit_default_mms_value(dat);

    Ok(quote! {
        DataAttribute::new(
            ::std::string::String::from(#name_lit),
            #parent_fc,
            #dat_tok,
            TrgOps::NONE,
            #initial_tok,
        )
    })
}

// -----------------------------------------------------------------------------
// 5. DataSet / FCDA
// -----------------------------------------------------------------------------

fn emit_dataset_expr(
    ds: &RawDataSet,
    ld_inst: &str,
    ln: &RawLogicalNode,
) -> Result<TokenStream, CompileError> {
    let name_lit = ds.name.as_str();
    let entries = ds
        .fcdas
        .iter()
        .map(|f| emit_fcda_expr(f, ld_inst, ln))
        .collect::<Result<Vec<_>, _>>()?;
    Ok(quote! {
        DataSet {
            name: ::std::string::String::from(#name_lit),
            entries: ::std::vec![ #( #entries ),* ],
        }
    })
}

fn emit_fcda_expr(
    f: &RawFcda,
    _ld_inst: &str,
    _ln: &RawLogicalNode,
) -> Result<TokenStream, CompileError> {
    let ld_inst_lit = f.ld_inst.as_str();

    // ln_name is prefix + ln_class + ln_inst, with an empty instance treated as "".
    let mut ln_name = String::new();
    if let Some(p) = &f.prefix {
        ln_name.push_str(p);
    }
    ln_name.push_str(&f.ln_class);
    if let Some(i) = &f.ln_inst {
        ln_name.push_str(i);
    }

    let fc = parse_fc(&f.fc, f.span, "FCDA").map_err(CompileError::ResolveScl)?;
    let fc_tok = emit_fc_value(fc);

    // do_path splits doName on `.`; daName becomes the final segment.
    let mut do_path: Vec<String> = Vec::new();
    if let Some(do_name) = &f.do_name {
        for seg in do_name.split('.') {
            if !seg.is_empty() {
                do_path.push(seg.to_string());
            }
        }
    }
    if let Some(da_name) = &f.da_name {
        do_path.push(da_name.clone());
    }
    let do_path_lits: Vec<&str> = do_path.iter().map(|s| s.as_str()).collect();

    let array_index_tok = match f.ix {
        Some(i) => quote! { ::std::option::Option::Some(#i) },
        None => quote! { ::std::option::Option::None },
    };

    Ok(quote! {
        DataSetEntry {
            ld_inst: ::std::string::String::from(#ld_inst_lit),
            ln_name: ::std::string::String::from(#ln_name),
            fc: #fc_tok,
            do_path: ::std::vec![ #( ::std::string::String::from(#do_path_lits) ),* ],
            array_index: #array_index_tok,
            component: ::std::option::Option::None,
        }
    })
}

