/// One `<DAI>`: the path from the logical node, the data object name first,
/// the parsed value, and the parsed value of each setting group.
#[derive(Debug, Clone, PartialEq)]
struct DaiOverride {
    /// The data object name, then each `<SDI>` and `<DAI>` name with its `ix`.
    path: Vec<(String, Option<u32>)>,
    value: MmsValue,
    sgroup_values: Vec<(u8, MmsValue)>,
}

/// Emits the statements that apply every DAI value under `RawLogicalNode.doi`
/// to the built logical node `__ln`.
///
/// DAI strings are parsed while the build script runs, through the runtime
/// `dai_values` helper, and the result is emitted as a literal by
/// `emit_mms_value`, so the user's run time performs no string parsing. Each
/// statement reaches its attributes through `apply_to_instance`, which walks
/// sub-objects, data attributes and nested attributes alike and reaches both
/// attributes of an FC=SE and FC=SG setting; a path that does not resolve is
/// skipped, as on the runtime path.
fn emit_doi_overrides(
    ln: &RawLogicalNode,
    dtt: &DataTypeTemplates,
    ld_inst: &str,
    num_of_sgs: Option<u32>,
) -> Result<Vec<TokenStream>, CompileError> {
    Ok(collect_doi_overrides(ln, dtt, ld_inst, num_of_sgs)?
        .iter()
        .map(emit_dai_override)
        .collect())
}

/// Emits the write of one DAI value into every attribute its path reaches.
fn emit_dai_override(o: &DaiOverride) -> TokenStream {
    let (do_name, rest) = match o.path.split_first() {
        Some((first, rest)) => (first.0.as_str(), rest),
        None => ("", &[][..]),
    };
    let names: Vec<&str> = rest.iter().map(|(s, _)| s.as_str()).collect();
    let indices: Vec<TokenStream> = rest
        .iter()
        .map(|(_, ix)| match ix {
            Some(i) => quote! { ::core::option::Option::Some(#i) },
            None => quote! { ::core::option::Option::None },
        })
        .collect();
    let value_tok = emit_mms_value(&o.value);
    let sgroups = (!o.sgroup_values.is_empty()).then(|| {
        let groups = o.sgroup_values.iter().map(|(g, _)| *g);
        let values = o.sgroup_values.iter().map(|(_, v)| emit_mms_value(v));
        quote! {
            __da.sgroup_values = ::std::vec![ #( (#groups, #values) ),* ];
        }
    });
    quote! {
        ::iec61850_scl::__private::apply_to_instance(
            &mut __ln,
            #do_name,
            &[ #( (#names, #indices) ),* ],
            |__da| {
                __da.store(#value_tok);
                #sgroups
            },
        );
    }
}

/// Flattens every DAI under `RawLogicalNode.doi` into a [`DaiOverride`].
///
/// A failing override, such as a DAI landing on a constructed DA, is reported
/// while the build script runs instead of being carried into the user's
/// binary.
fn collect_doi_overrides(
    ln: &RawLogicalNode,
    dtt: &DataTypeTemplates,
    ld_inst: &str,
    num_of_sgs: Option<u32>,
) -> Result<Vec<DaiOverride>, CompileError> {
    let lnt = dtt.ln_node_types.get(&ln.ln_type_ref).ok_or_else(|| {
        CompileError::Emit(format!(
            "LN ln_type_ref `{}` is absent from ln_node_types; the resolve stage should have rejected it",
            ln.ln_type_ref
        ))
    })?;

    let mut out: Vec<DaiOverride> = Vec::new();
    for raw_doi in &ln.doi {
        let raw_do_def = match lnt.dos.iter().find(|d| d.name == raw_doi.name) {
            Some(d) => d,
            None => {
                tracing::warn!(
                    target: "iec61850-scl-build",
                    "DOI name=\"{}\" has no matching DO in LNodeType id=\"{}\", skipping",
                    raw_doi.name,
                    lnt.id
                );
                continue;
            }
        };
        let dot = dtt.do_types.get(&raw_do_def.do_type_ref).ok_or_else(|| {
            CompileError::Emit(format!(
                "DO type_ref `{}` is absent from do_types; the resolve stage should have rejected it",
                raw_do_def.do_type_ref
            ))
        })?;
        let path_prefix = format!(
            "SCL/.../LDevice[inst=\"{}\"]/LN[lnClass=\"{}\",inst=\"{}\"]/DOI[name=\"{}\"]",
            ld_inst, ln.ln_class, ln.inst, raw_doi.name
        );
        // path_segments is the path from the logical node down to the data
        // attribute: the DO name first, then the SDI and DAI names.
        let mut base_path: Vec<(String, Option<u32>)> = vec![(raw_doi.name.clone(), None)];
        let ctx = EmitContext { dtt, num_of_sgs };
        emit_instances_at_do(
            &raw_doi.children,
            dot,
            &ctx,
            &path_prefix,
            &mut base_path,
            &mut out,
        )?;
    }

    Ok(out)
}

/// What the instance walk carries down: the type tables and the setting group
/// count of the logical device.
struct EmitContext<'a> {
    dtt: &'a DataTypeTemplates,
    num_of_sgs: Option<u32>,
}

/// Flattens the SDI and DAI children of a DOType or DAType container into emit
/// statements.
///
/// `base_path` is the path from the logical node to the current position:
/// segment 0 is the DO name, followed by the SDO and SDA names. Each DAI becomes
/// one statement that walks the tree and writes the value.
fn emit_instances_at_do(
    children: &[RawDataInstance],
    dot: &RawDoType,
    ctx: &EmitContext<'_>,
    parent_path: &str,
    base_path: &mut Vec<(String, Option<u32>)>,
    out: &mut Vec<DaiOverride>,
) -> Result<(), CompileError> {
    for inst in children {
        match inst {
            RawDataInstance::Sdi(sdi) => {
                handle_sdi_at_do(sdi, dot, ctx, parent_path, base_path, out)?;
            }
            RawDataInstance::Dai(dai) => {
                let da_def = match dot.das().find(|d| d.name == dai.name) {
                    Some(d) => d,
                    None => {
                        tracing::warn!(
                            target: "iec61850-scl-build",
                            "DAI name=\"{}\" has no matching DA in DOType id=\"{}\", skipping",
                            dai.name,
                            dot.id
                        );
                        continue;
                    }
                };
                if !element_matches("DAI", &dai.name, da_def.count.as_ref(), dai.ix) {
                    continue;
                }
                let path = format!("{}/DAI[name=\"{}\"]", parent_path, dai.name);
                base_path.push((dai.name.clone(), dai.ix));
                emit_dai_assignment(
                    dai,
                    da_def.b_type.as_str(),
                    da_def.type_ref.as_deref(),
                    ctx,
                    &path,
                    base_path,
                    out,
                )?;
                base_path.pop();
            }
        }
    }
    Ok(())
}

/// Reports whether the `ix` of an `<SDI>` or `<DAI>` matches the `count` of
/// the declaration it names, and warns when it does not, as the runtime path
/// skips such an instance: an index needs an array and must lie below its
/// count, and an array needs an index.
fn element_matches(kind: &str, name: &str, count: Option<&RawCount>, ix: Option<u32>) -> bool {
    // A count the instance gives is known only to the model builder, which
    // skips a mismatched instance itself when the generated code runs.
    if matches!(count, Some(RawCount::Attribute(_))) {
        return true;
    }
    let matches = match (count.and_then(RawCount::elements), ix) {
        (None, None) => true,
        (Some(n), Some(i)) => i < n,
        _ => false,
    };
    if !matches {
        tracing::warn!(
            target: "iec61850-scl-build",
            "{} name=\"{}\" ix=\"{:?}\" does not match the array it names, skipping",
            kind,
            name,
            ix
        );
    }
    matches
}

fn handle_sdi_at_do(
    sdi: &RawSdi,
    dot: &RawDoType,
    ctx: &EmitContext<'_>,
    parent_path: &str,
    base_path: &mut Vec<(String, Option<u32>)>,
    out: &mut Vec<DaiOverride>,
) -> Result<(), CompileError> {
    // Two possibilities: a sub-DO, or a constructed DA with bType=Struct.
    if let Some(sdo) = dot.sdos().find(|s| s.name == sdi.name) {
        let sub_dot = ctx.dtt.do_types.get(&sdo.do_type_ref).ok_or_else(|| {
            CompileError::Emit(format!(
                "SDO type_ref `{}` is absent from do_types; the resolve stage should have rejected it",
                sdo.do_type_ref
            ))
        })?;
        if !element_matches("SDI", &sdi.name, sdo.count.as_ref(), sdi.ix) {
            return Ok(());
        }
        let path = format!("{}/SDI[name=\"{}\"]", parent_path, sdi.name);
        base_path.push((sdi.name.clone(), sdi.ix));
        emit_instances_at_do(&sdi.children, sub_dot, ctx, &path, base_path, out)?;
        base_path.pop();
    } else if let Some(da_def) = dot.das().find(|d| d.name == sdi.name) {
        if da_def.b_type != "Struct" {
            tracing::warn!(
                target: "iec61850-scl-build",
                "SDI name=\"{}\" resolves to a DA that is not a Struct (bType=\"{}\"), skipping",
                sdi.name,
                da_def.b_type
            );
            return Ok(());
        }
        let type_id = da_def.type_ref.as_deref().ok_or_else(|| {
            CompileError::Emit(format!(
                "DA `{}` has bType=Struct but no type_ref; the resolve stage should have rejected it",
                da_def.name
            ))
        })?;
        let dat = ctx.dtt.da_types.get(type_id).ok_or_else(|| {
            CompileError::Emit(format!(
                "DA type_ref `{}` is absent from da_types; the resolve stage should have rejected it",
                type_id
            ))
        })?;
        if !element_matches("SDI", &sdi.name, da_def.count.as_ref(), sdi.ix) {
            return Ok(());
        }
        let path = format!("{}/SDI[name=\"{}\"]", parent_path, sdi.name);
        base_path.push((sdi.name.clone(), sdi.ix));
        emit_instances_at_da(&sdi.children, dat, ctx, &path, base_path, out)?;
        base_path.pop();
    } else {
        tracing::warn!(
            target: "iec61850-scl-build",
            "SDI name=\"{}\" has no matching SDO or DA in DOType id=\"{}\", skipping",
            sdi.name,
            dot.id
        );
    }
    Ok(())
}

fn emit_instances_at_da(
    children: &[RawDataInstance],
    dat: &RawDaType,
    ctx: &EmitContext<'_>,
    parent_path: &str,
    base_path: &mut Vec<(String, Option<u32>)>,
    out: &mut Vec<DaiOverride>,
) -> Result<(), CompileError> {
    for inst in children {
        match inst {
            RawDataInstance::Sdi(sdi) => {
                let bda_def = match dat.bdas.iter().find(|b| b.name == sdi.name) {
                    Some(b) => b,
                    None => {
                        tracing::warn!(
                            target: "iec61850-scl-build",
                            "SDI name=\"{}\" has no matching BDA in DAType id=\"{}\", skipping",
                            sdi.name,
                            dat.id
                        );
                        continue;
                    }
                };
                if bda_def.b_type != "Struct" {
                    tracing::warn!(
                        target: "iec61850-scl-build",
                        "SDI name=\"{}\" resolves to a BDA that is not a Struct (bType=\"{}\"), skipping",
                        sdi.name,
                        bda_def.b_type
                    );
                    continue;
                }
                let type_id = bda_def.type_ref.as_deref().ok_or_else(|| {
                    CompileError::Emit(format!(
                        "BDA `{}` has bType=Struct but no type_ref; the resolve stage should have rejected it",
                        bda_def.name
                    ))
                })?;
                let sub_dat = ctx.dtt.da_types.get(type_id).ok_or_else(|| {
                    CompileError::Emit(format!(
                        "BDA type_ref `{}` is absent from da_types; the resolve stage should have rejected it",
                        type_id
                    ))
                })?;
                if !element_matches("SDI", &sdi.name, bda_def.count.as_ref(), sdi.ix) {
                    continue;
                }
                let path = format!("{}/SDI[name=\"{}\"]", parent_path, sdi.name);
                base_path.push((sdi.name.clone(), sdi.ix));
                emit_instances_at_da(&sdi.children, sub_dat, ctx, &path, base_path, out)?;
                base_path.pop();
            }
            RawDataInstance::Dai(dai) => {
                let bda_def = match dat.bdas.iter().find(|b| b.name == dai.name) {
                    Some(b) => b,
                    None => {
                        tracing::warn!(
                            target: "iec61850-scl-build",
                            "DAI name=\"{}\" has no matching BDA in DAType id=\"{}\", skipping",
                            dai.name,
                            dat.id
                        );
                        continue;
                    }
                };
                if !element_matches("DAI", &dai.name, bda_def.count.as_ref(), dai.ix) {
                    continue;
                }
                let path = format!("{}/DAI[name=\"{}\"]", parent_path, dai.name);
                base_path.push((dai.name.clone(), dai.ix));
                emit_dai_assignment(
                    dai,
                    bda_def.b_type.as_str(),
                    bda_def.type_ref.as_deref(),
                    ctx,
                    &path,
                    base_path,
                    out,
                )?;
                base_path.pop();
            }
        }
    }
    Ok(())
}

/// Parses one DAI value while the build script runs and records it with its
/// path from the logical node.
fn emit_dai_assignment(
    dai: &RawDai,
    b_type: &str,
    type_ref: Option<&str>,
    ctx: &EmitContext<'_>,
    path: &str,
    base_path: &[(String, Option<u32>)],
    out: &mut Vec<DaiOverride>,
) -> Result<(), CompileError> {
    if dai.values.is_empty() {
        // No Val element: the DAI only declares valKind or valImport and
        // overrides no value, exactly as at run time.
        return Ok(());
    }
    if b_type == "Struct" {
        return Err(CompileError::Emit(format!(
            "{}: the DAI resolves to a constructed DA (bType=Struct); an SDI is required here, and the runtime path rejects it too",
            path
        )));
    }
    let (value, sgroup_values) =
        dai_values(dai, b_type, type_ref, ctx.dtt, ctx.num_of_sgs, path).map_err(model_error)?;
    if base_path.is_empty() {
        return Err(CompileError::Emit(format!(
            "{}: the DAI override path is empty",
            path
        )));
    }
    out.push(DaiOverride {
        path: base_path.to_vec(),
        value,
        sgroup_values,
    });
    Ok(())
}

