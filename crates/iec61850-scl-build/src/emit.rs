/// Converts an IED name into a valid Rust identifier. The SCL schema allows
/// `[A-Za-z_][A-Za-z0-9_]*`; any other character is stripped for safety.
fn sanitize_ident(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    for c in name.chars() {
        if c.is_ascii_alphanumeric() || c == '_' {
            out.push(c);
        } else {
            out.push('_');
        }
    }
    if out.is_empty() || out.chars().next().is_some_and(|c| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    out
}

fn sorted_by_name<'a, T, F>(
    iter: impl Iterator<Item = &'a T>,
    cfg: &CompileBuilder,
    key: F,
) -> Vec<&'a T>
where
    T: 'a,
    F: Fn(&T) -> &str,
{
    let mut v: Vec<&T> = iter.collect();
    if cfg.is_deterministic() {
        v.sort_by(|a, b| key(a).cmp(key(b)));
    }
    v
}

