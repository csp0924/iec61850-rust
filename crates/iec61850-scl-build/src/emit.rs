/// Emits a logical device as a
/// `LogicalDeviceBuilder::new(...).add_ln(...).build()` expression.
fn emit_ld_expr(
    ld: &RawLogicalDevice,
    dtt: &DataTypeTemplates,
    ied_name: &str,
    cfg: &CompileBuilder,
) -> Result<TokenStream, CompileError> {
    let domain = ld_domain_name(ld, ied_name);
    let inst_lit = ld.inst.as_str();
    let with_ld_name = ld.ld_name.as_deref().map(|n| {
        quote! { __ld = __ld.with_ld_name(#n); }
    });

    // Deterministic mode sorts the logical nodes by (prefix, class, inst), but
    // LLN0 has to stay first: the model builder rejects any other order with
    // InvalidParent.
    let mut lns: Vec<&RawLogicalNode> = ld.logical_nodes.iter().collect();
    if cfg.is_deterministic() {
        lns.sort_by(|a, b| {
            // LLN0 always sorts first; otherwise compare (prefix, class, inst).
            let a_is_lln0 = a.ln_class == "LLN0";
            let b_is_lln0 = b.ln_class == "LLN0";
            match (a_is_lln0, b_is_lln0) {
                (true, false) => std::cmp::Ordering::Less,
                (false, true) => std::cmp::Ordering::Greater,
                _ => (
                    a.prefix.as_deref().unwrap_or(""),
                    a.ln_class.as_str(),
                    a.inst.as_str(),
                )
                    .cmp(&(
                        b.prefix.as_deref().unwrap_or(""),
                        b.ln_class.as_str(),
                        b.inst.as_str(),
                    )),
            }
        });
    }

    let num_of_sgs = ld_num_of_sgs(ld);
    let ln_exprs = lns
        .iter()
        .map(|ln| emit_ln_expr(ln, dtt, &ld.inst, &domain, num_of_sgs, cfg))
        .collect::<Result<Vec<_>, _>>()?;

    Ok(quote! {
        {
            let mut __ld = LogicalDeviceBuilder::new(#inst_lit);
            #with_ld_name
            #(
                __ld = __ld.add_ln(#ln_exprs);
            )*
            __ld.build().expect("codegen: LogicalDeviceBuilder::build failed")
        }
    })
}

