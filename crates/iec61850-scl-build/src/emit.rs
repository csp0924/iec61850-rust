// 5. DataSet / FCDA
// -----------------------------------------------------------------------------

fn emit_dataset_expr(
    ds: &RawDataSet,
    ld_inst: &str,
    ln: &RawLogicalNode,
) -> Result<TokenStream, CompileError> {
    let name_lit = ds.name.as_str();
    let entries = ds
        .fcdas
        .iter()
        .map(|f| emit_fcda_expr(f, ld_inst, ln))
        .collect::<Result<Vec<_>, _>>()?;
    Ok(quote! {
        DataSet::new(
            ::std::string::String::from(#name_lit),
            ::std::vec![ #( #entries ),* ],
        )
    })
}

fn emit_fcda_expr(
    f: &RawFcda,
    _ld_inst: &str,
    _ln: &RawLogicalNode,
) -> Result<TokenStream, CompileError> {
    let ld_inst_lit = f.ld_inst.as_str();

    // ln_name is prefix + ln_class + ln_inst, with an empty instance treated as "".
    let mut ln_name = String::new();
    if let Some(p) = &f.prefix {
        ln_name.push_str(p);
    }
    ln_name.push_str(&f.ln_class);
    if let Some(i) = &f.ln_inst {
        ln_name.push_str(i);
    }

    let fc = parse_fc(&f.fc, f.span, "FCDA").map_err(model_error)?;
    let fc_tok = emit_fc_value(fc);

    // do_path and the array index come from the runtime helper.
    let (do_path, array_index) = fcda_do_path(
        f.do_name.as_deref(),
        f.da_name.as_deref(),
        f.ix,
        f.span,
        "FCDA",
    )
    .map_err(model_error)?;
    let do_path_lits: Vec<&str> = do_path.iter().map(|s| s.as_str()).collect();

    let array_index_tok = match array_index {
        Some(i) => quote! { ::std::option::Option::Some(#i) },
        None => quote! { ::std::option::Option::None },
    };

    Ok(quote! {
        {
            let mut __entry = DataSetEntry::new(
                ::std::string::String::from(#ln_name),
                #fc_tok,
                ::std::vec![ #( ::std::string::String::from(#do_path_lits) ),* ],
            );
            __entry.ld_inst = ::std::string::String::from(#ld_inst_lit);
            __entry.array_index = #array_index_tok;
            __entry
        }
    })
}

